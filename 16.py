from lesson_base import lesson, theory, code, quiz, practice

LESSON = lesson(
    id=16,
    chapter="Шаблоны и упаковка",
    title="copyFrom, шаблоны и mod-info",
    subtitle="Как не писать одно и то же сто раз",
    pages=[
        theory("copyFrom",
               "`copyFrom` берёт настройки из другого файла как основу, а твои строки "
               "их перезаписывают. Можно указать несколько файлов через запятую.\n"
               "`ROOT:` означает корень мода: `copyFrom: ROOT:templates/hull.template`\n"
               "Файлы `.template` — обычные файлы с общими секциями, но игра не грузит их "
               "как юниты, пока на них не сошлётся `copyFrom`."),
        theory("Шаблоны и переменные",
               "`[template_имя]` — секция-заготовка внутри файла, которую можно подтянуть "
               "в любую другую секцию через `@copyFromSection`.\n"
               "`@copyFrom_skipThisSection` — не копировать эту секцию из `copyFrom`.\n"
               "`@define имя: значение` — локальная переменная раздела, `@global` — на весь файл; "
               "используй её как `${имя}` и даже с математикой: `${core.price * 2 + 10}`.\n"
               "`@memory имя: тип` — удобный способ объявить память юнита.\n"
               "`%{выражение}` — живая логика в тексте, обновляется каждый кадр: "
               "`Не хватает: %{self.maxHp - self.hp}`.\n"
               "`all-units.template` в корне мода применяется ко **всем** `.ini` файлам мода — "
               "идеально для общих настроек."),
        theory("mod-info.txt",
               "Файл `mod-info.txt` в корне мода описывает мод для браузера модов и Steam Workshop. "
               "Без него в корне будет ошибка.\n"
               "В секции `[mod]`: `title` — название, `description` — описание, `tags` — теги через запятую, "
               "`minVersion` — минимальная версия игры (обязательно укажи, если используешь декали и другие ключи 1.15p9+), `thumbnail` — картинка-превью.\n"
               "В секции `[music]` можно задать папку с музыкой мода."),
        theory("Финальные советы",
               "• Держи официальную справку открытой и ищи по ней через `Ctrl+F` — там есть всё, включая этот курс "
               "(в самом верху файла есть таблица содержания, а в самом низу — список встроенных звуков, спрайтов снарядов и таблица `drawType`)\n"
               "• Начинай с турелей и снарядов — это самый быстрый путь к юниту в ванильном стиле\n"
               "• Ошибка загрузки почти всегда называет секцию и ключ, которых не хватает\n"
               "• Используй `#` для заметок прямо в `.ini`\n"
               "• Не бойся экспериментировать: сломанный юнит ломает только себя"),
        code("Шаблон и его использование",
             "[core]\n"
             "copyFrom: ROOT:templates/hull.template, tankT1.ini\n"
             "name: tankT2\n"
             "maxHp: 500",
             note="Всё общее живёт в .template, в юните — только отличия."),
        code("all-units.template",
             "[core]\n"
             "strictLevel: 1\n"
             "explodeTypeOnDeath: normal",
             note="Эти строки применятся к каждому юниту мода."),
        code("mod-info.txt",
             "[mod]\n"
             "title: Мой первый мод\n"
             "description: Набор танков и турелей\n"
             "tags: units, tanks\n"
             "minVersion: 1.13"),
        quiz("Какой файл применяется ко ВСЕМ юнитам мода?",
             ["mod-info.txt", "NAME.template", "all-units.template", "progress.json"], 2,
             explain="Положи all-units.template в корень мода — и его ключи получат все юниты."),
        quiz("Какой префикс указывает на корень мода в путях?",
             ["ROOT:", "BASE:", "MOD:", "DIR:"], 0,
             explain="copyFrom: ROOT:путь/файл.template ищет файл от корня мода."),
        practice("Оформи mod-info: название и минимальная версия",
                 "[mod]\n"
                 "___1___: Мой первый мод\n"
                 "description: Мод с танками\n"
                 "___2___: 1.13",
                 {"1": "title", "2": "minVersion"},
                 hint="Название мода задаёт key title.",
                 explain="Поздравляю — ты прошёл весь курс! Теперь у тебя есть все ключи для своих модов."),
    ],
)