from lesson_base import lesson, theory, code, quiz, practice

LESSON = lesson(
    id=3,
    chapter="Базовые секции",
    title="[core] — сердце юнита",
    subtitle="Здоровье, цена, масса и радиус",
    pages=[
        theory("Что живёт в [core]",
               "`[core]` — паспорт юнита. Здесь лежат его главные характеристики:\n\n"
               "• `name` — внутреннее имя. Игрок его не видит, но игра использует "
               "для всех ссылок. Должно быть уникальным!\n"
               "• `displayText` — а вот это имя игрок видит на экране\n"
               "• `maxHp` — максимальное здоровье\n"
               "• `price` — цена постройки. По умолчанию в кредитах: `price: 500`\n"
               "• `mass` — масса. Чем больше, тем труднее столкнуть юнит\n"
               "• `radius` — радиус выделения юнита мышкой/пальцем"),
        theory("Полезные ключи [core]",
               "• `buildSpeed: 3s` — время постройки\n"
               "• `techLevel: 1` — техуровень (1–3), влияет на цвет в меню\n"
               "• `selfRegenRate` — пассивная регенерация здоровья\n"
               "• `maxShield` / `shieldRegen` — щит и его восстановление\n"
               "• `energyMax` / `energyRegen` — энергия, работает как боезапас для оружия\n"
               "• `tags: tank, heavy` — ярлыки для логики и балансов\n"
               "• `isBuilding: true` — юнит является зданием"),
        code("Ядро тяжёлого танка",
             "[core]\n"
             "name: heavyTank\n"
             "displayText: Тяжёлый танк\n"
             "displayDescription: -Медленный\\n-Очень крепкий\n"
             "maxHp: 900\n"
             "price: 1200\n"
             "mass: 3000\n"
             "radius: 18\n"
             "buildSpeed: 5s\n"
             "techLevel: 2\n"
             "tags: tank, heavy"),
        quiz("Какой ключ задаёт максимальное здоровье?",
             ["price", "mass", "maxHp", "radius"], 2,
             explain="maxHp — health points. Юнит появляется с этим запасом здоровья."),
        quiz("За что отвечает масса (mass)?",
             ["за цену юнита", "за столкновения и толкание", "за здоровье", "за дальность атаки"], 1,
             explain="Большая масса = юнит тяжело сдвинуть с места при столкновении."),
        practice("Заполни паспорт тяжёлого танка: впиши недостающие ключи",
                 "[core]\n"
                 "___1___: heavyTank\n"
                 "___2___: 900\n"
                 "price: 1200\n"
                 "mass: 3000\n"
                 "___3___: 18\n"
                 "___4___: Тяжёлый танк",
                 {"1": "name", "2": "maxHp", "3": "radius", "4": "displayText"},
                 hint="900 — это здоровье, 18 — радиус выделения.",
                 explain="name и displayText — разные вещи: первое для игры, второе для игрока."),
    ],
)