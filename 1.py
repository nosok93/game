from lesson_base import lesson, theory, code, quiz, practice

LESSON = lesson(
    id=1,
    chapter="Курс молодого бойца",
    title="Что такое моддинг RW",
    subtitle="Файлы, папки и правила игры",
    pages=[
        theory("Добро пожаловать!",
               "Моддинг в Rusted Warfare — это создание собственных юнитов, зданий и механик "
               "с помощью обычных **текстовых файлов**. Никакого компилятора: ты просто описываешь "
               "юнит словами, а игра читает это описание.\n\n"
               "Один юнит = один файл с расширением `.ini`. Имя файла может быть любым: "
               "`tank.ini`, `robot.ini`, хоть `мой_юнит.ini`."),
        theory("Где живут файлы",
               "Игра ищет моды по пути:\n"
               "`rustedWarfare/mods/units/ИМЯ_МОДА/`\n\n"
               "• `ИМЯ_МОДА` — папка твоего мода, название придумываешь сам\n"
               "• внутри лежат `.ini` файлы юнитов и картинки `.png`\n\n"
               "Игра при запуске сама найдёт и загрузит всё, что там лежит."),
        theory("Секции — скелет юнита",
               "Файл юнита состоит из **секций** — блоков в квадратных скобках: "
               "`[core]`, `[graphics]`, `[attack]`, `[movement]` и других.\n\n"
               "• **Одиночные** — только одна на файл: `[core]`, `[graphics]`, `[attack]`\n"
               "• **Множественные** — с именем, их может быть сколько угодно: "
               "`[turret_1]`, `[turret_2]`, `[projectile_shot]`\n\n"
               "Дальше по курсу каждую секцию разберём отдельно."),
        code("Скелет будущего юнита",
             "[core]\n"
             "name: myUnit\n"
             "maxHp: 200\n"
             "\n"
             "[graphics]\n"
             "image: body.png\n"
             "\n"
             "[attack]\n"
             "canAttack: true\n"
             "\n"
             "[movement]\n"
             "movementType: LAND",
             note="Пока это заготовка. К концу курса ты соберёшь из неё полноценный танк."),
        quiz("Файл какого формата описывает юнита?",
             [".png", ".ini", ".txt", ".rw"], 1,
             explain="Юнит описывается в файле .ini — это обычный текст с настройками."),
        quiz("Где должна лежать папка твоего мода?",
             ["rustedWarfare/save/", "documents/", "rustedWarfare/mods/units/", "рабочий стол/"], 2,
             explain="Полный путь: rustedWarfare/mods/units/ИМЯ_МОДА/."),
        practice("Впиши пропущенные части пути к файлу юнита",
                 "rustedWarfare/mods/___1___/MyFirstMod/tank.___2___",
                 {"1": "units", "2": "ini"},
                 hint="Первое — папка с юнитами, второе — расширение файла.",
                 explain="Все юниты лежат в mods/units/, а файлы юнитов имеют расширение .ini."),
    ],
)